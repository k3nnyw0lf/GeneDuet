// Generates a realistic, Mendelian-consistent DEMO trio (synthetic — NOT real DNA)
// for screenshots/UI demos: ~3000 autosomal SNPs (so KING reads parent–child),
// every catalog marker with clean genotypes, and X/Y so genetic sex works.
// dad = male, mom = female, son = their child.
import { writeFileSync } from "node:fs";
import { CATALOG } from "../data/catalog.mjs";

const al = () => (Math.random() < 0.5 ? "A" : "G");
const pick = (g) => g[Math.random() < 0.5 ? 0 : 1];
const sort2 = (a, b) => [a, b].sort().join("");
const dad = [], mom = [], son = [];
let pos = 1000;

// autosomal trio (child inherits one allele from each parent)
for (let i = 0; i < 3000; i++) {
  pos += 10; const d = al() + al(), m = al() + al();
  dad.push(`rsa${i}\t1\t${pos}\t${d}`); mom.push(`rsa${i}\t1\t${pos}\t${m}`);
  son.push(`rsa${i}\t1\t${pos}\t${sort2(pick(d), pick(m))}`);
}
// catalog markers: dad hom allele[0], mom hom allele[1], child het (clean + parent-of-origin resolvable)
const MODEL = { rs429358: ["TT", "CT", "CT"], rs7412: ["CC", "CC", "CC"], rs80357914: ["II", "II", "II"],
  rs80357906: ["II", "II", "II"], rs80359550: ["II", "II", "II"], rs4244285: ["GG", "AG", "AG"],
  rs12248560: ["CC", "CT", "CC"], rs9923231: ["GG", "AG", "AG"], rs1799853: ["CC", "CT", "CC"], rs1057910: ["AA", "AC", "AA"] };
const seen = new Set();
for (const e of CATALOG) {
  for (const rs of e.rsid ? [e.rsid] : (e.snps || [])) {
    if (seen.has(rs)) continue; seen.add(rs); pos += 10;
    let d, m, s;
    if (MODEL[rs]) [d, m, s] = MODEL[rs];
    else if (e.alleles) { const [x, y] = e.alleles; d = x + x; m = y + y; s = sort2(x, y); }
    else d = m = s = "II";
    dad.push(`${rs}\t1\t${pos}\t${d}`); mom.push(`${rs}\t1\t${pos}\t${m}`); son.push(`${rs}\t1\t${pos}\t${s}`);
  }
}
// sex chromosomes: males (dad, son) = homozygous X + called Y; female (mom) = heterozygous X, no Y
for (let i = 0; i < 1000; i++) {
  dad.push(`rsx${i}\t23\t${i + 1}\tAA`); son.push(`rsx${i}\t23\t${i + 1}\tAA`);
  mom.push(`rsx${i}\t23\t${i + 1}\t${i % 2 ? "AG" : "AA"}`);
}
for (let i = 0; i < 300; i++) { dad.push(`rsy${i}\t24\t${i + 1}\tA`); son.push(`rsy${i}\t24\t${i + 1}\tA`); }

const hdr = "# This data file generated by 23andMe\n# rsid\tchromosome\tposition\tgenotype\n";
writeFileSync("tools/fixtures/demo_dad.txt", hdr + dad.join("\n") + "\n");
writeFileSync("tools/fixtures/demo_mom.txt", hdr + mom.join("\n") + "\n");
writeFileSync("tools/fixtures/demo_son.txt", hdr + son.join("\n") + "\n");
console.log(`demo trio: dad ${dad.length}, mom ${mom.length}, son ${son.length} rows`);

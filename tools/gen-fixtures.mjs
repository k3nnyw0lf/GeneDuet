// Dev tool: generate a synthetic, Mendelian-consistent trio covering the whole
// catalog so we can smoke-test reports without real DNA. 23andMe text format.
import { writeFileSync } from "node:fs";
import { CATALOG } from "../data/catalog.mjs";

const rsids = new Map(); // rsid -> alleles (or null for model/indel sites)
for (const e of CATALOG) {
  if (e.rsid) rsids.set(e.rsid, e.alleles);
  if (e.snps) for (const s of e.snps) if (!rsids.has(s)) rsids.set(s, null);
}
// model-site genotypes chosen to be interesting + consistent
const MODEL = {
  rs429358: ["TT", "CT", "CT"], rs7412: ["CC", "CC", "CC"],          // APOE e3/e3 × e3/e4
  rs80357914: ["II", "II", "II"], rs80357906: ["II", "II", "II"], rs80359550: ["II", "II", "II"],
  rs4244285: ["GG", "AG", "AG"], rs12248560: ["CC", "CT", "CC"],     // clopidogrel
  rs9923231: ["GG", "AG", "AG"], rs1799853: ["CC", "CT", "CC"], rs1057910: ["AA", "AC", "AA"], // warfarin
};

const dad = [], mom = [], son = [];
let pos = 1000;
for (const [rs, alleles] of rsids) {
  pos += 10;
  let d, m, s;
  if (MODEL[rs]) { [d, m, s] = MODEL[rs]; }
  else if (alleles) {
    const [x, y] = alleles;
    d = x + x; m = y + y; s = [x, y].sort().join(""); // dad hom A, mom hom B, son het (consistent)
  } else { d = m = s = "II"; }
  const row = (gt) => `${rs}\t1\t${pos}\t${gt}`;
  dad.push(row(d)); mom.push(row(m)); son.push(row(s));
}
const hdr = "# This data file generated by 23andMe\n# rsid\tchromosome\tposition\tgenotype\n";
writeFileSync("tools/fixtures/dad.txt", hdr + dad.join("\n") + "\n");
writeFileSync("tools/fixtures/mom.txt", hdr + mom.join("\n") + "\n");
writeFileSync("tools/fixtures/son.txt", hdr + son.join("\n") + "\n");
console.log(`wrote trio fixtures covering ${rsids.size} sites`);
